const fs=require('node:fs'),crypto=require('node:crypto');
const iconDirectory='assets/file-picker';
const pngFiles=fs.readdirSync(iconDirectory).filter(f=>f.endsWith('.png')).sort();
const icons=Object.fromEntries(pngFiles.map(name=>[name.slice(0,-4),'data:image/png;base64,'+fs.readFileSync(iconDirectory+'/'+name).toString('base64')]));
const pickerFile='file-pickers.js';
let picker=fs.readFileSync(pickerFile,'utf8');
picker=picker.replace(/\/\* PNG_ICONS_START \*\/[\s\S]*?\/\* PNG_ICONS_END \*\//,'/* PNG_ICONS_START */\nconst pickerIcons = '+JSON.stringify(icons)+';\n/* PNG_ICONS_END */');
fs.writeFileSync(pickerFile,picker);
const assets=['player-tools.js','library-upgrade.js','library-upgrade.css','file-pickers.js','audio-import.js'];
const hash=crypto.createHash('sha256');
for(const file of [...assets,'fresh-navigation-sw.js','mp3-encoder-worker.js'])hash.update(fs.readFileSync(file));
const version=hash.digest('hex').slice(0,16);
let html=fs.readFileSync('index.html','utf8');
for(const asset of assets)html=html.replace(new RegExp('(\\./'+asset.replaceAll('.','\\.')+'\\?)[^"\\s>]+','g'),'$1'+version);
fs.writeFileSync('index.html',html);console.log('Asset version '+version);
